-- Q18. Find all products whose price is greater than
-- the average price of all products.

-- WRITE BELOW
SELECT *
FROM products
WHERE Price > (
    SELECT AVG(Price)
    FROM products
);



-- Q19. Find all products whose price is greater than
-- the average price of their own category.
-- Use a CORRELATED SUBQUERY.

-- WRITE BELOW
SELECT
    p.Product_Name,
    p.Category,
    p.Price
FROM products p
WHERE p.Price > (
    SELECT AVG(p2.Price)
    FROM products p2
    WHERE p2.Category = p.Category
);



-- Q20. Find the customer who generated the highest
-- total Sales.
-- Display Customer_Name and Total_Sales.

-- WRITE BELOW
SELECT
    c.Customer_Name,
    SUM(o.Sales) AS Total_Sales
FROM customers c
INNER JOIN orders o
    ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name
HAVING SUM(o.Sales) = (
    SELECT MAX(Customer_Total)
    FROM (
        SELECT SUM(Sales) AS Customer_Total
        FROM orders
        GROUP BY Customer_ID
    ) AS customer_sales
);