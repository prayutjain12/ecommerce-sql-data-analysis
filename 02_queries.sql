-- Q16. Find total Sales generated by each customer.
-- Display Customer_Name and Total_Sales.

-- WRITE BELOW
SELECT
    c.Customer_Name,
    SUM(o.Sales) AS Total_Sales
FROM customers c
INNER JOIN orders o
    ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name;



-- Q17. Find customers whose total Sales are greater than 50000.

-- WRITE BELOW
SELECT
    c.Customer_Name,
    SUM(o.Sales) AS Total_Sales
FROM customers c
INNER JOIN orders o
    ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name
HAVING SUM(o.Sales) > 50000;



