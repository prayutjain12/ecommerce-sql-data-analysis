-- Q1. Display all customers who belong to the North region.

-- WRITE BELOW
SELECT *
FROM customers
WHERE Region = 'North';



-- Q2. Display all products whose price is greater than 20000.

-- WRITE BELOW
SELECT *
FROM products
WHERE Price > 20000;



-- Q3. Find all orders where Quantity is greater than 2
-- and Discount is greater than 0.

-- WRITE BELOW
SELECT *
FROM orders
WHERE Quantity > 2
  AND Discount > 0;



-- Q4. Display all customers whose city is either Jaipur,
-- Delhi or Mumbai.

-- WRITE BELOW
SELECT *
FROM customers
WHERE City IN ('Jaipur', 'Delhi', 'Mumbai');



-- Q5. Find all orders placed during January 2026.

-- WRITE BELOW
SELECT *
FROM orders
WHERE Order_Date BETWEEN '2026-01-01' AND '2026-01-31';



