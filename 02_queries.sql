-- Q6. Find the total Sales generated for each Category.

-- WRITE BELOW
SELECT
    Category,
    SUM(Sales) AS Total_Sales
FROM orders
GROUP BY Category;



-- Q7. Find the average Profit for each Payment Mode.

-- WRITE BELOW
SELECT
    Payment_Mode,
    AVG(Profit) AS Average_Profit
FROM orders
GROUP BY Payment_Mode;



-- Q8. Find the total Quantity sold for each Product_ID
-- and show only products with total Quantity greater than 10.

-- WRITE BELOW
SELECT
    Product_ID,
    SUM(Quantity) AS Total_Quantity
FROM orders
GROUP BY Product_ID
HAVING SUM(Quantity) > 10;



-- Q9. Find the total Sales for each Sales Channel
-- and sort from highest to lowest.

-- WRITE BELOW
SELECT
    Sales_Channel,
    SUM(Sales) AS Total_Sales
FROM orders
GROUP BY Sales_Channel
ORDER BY Total_Sales DESC;



-- Q10. Display the top 5 products based on total Sales.

-- WRITE BELOW
SELECT
    Product_ID,
    SUM(Sales) AS Total_Sales
FROM orders
GROUP BY Product_ID
ORDER BY Total_Sales DESC
LIMIT 5;



