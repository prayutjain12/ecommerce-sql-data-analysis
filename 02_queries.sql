-- Q11. Display Order_ID, Customer_Name, City and Order_Date
-- by joining orders and customers.

-- WRITE BELOW
SELECT
    o.Order_ID,
    c.Customer_Name,
    c.City,
    o.Order_Date
FROM orders o
INNER JOIN customers c
    ON o.Customer_ID = c.Customer_ID;



-- Q12. Display all customers along with their orders.
-- Customers without any order should also be displayed.

-- WRITE BELOW
SELECT
    c.Customer_ID,
    c.Customer_Name,
    o.Order_ID,
    o.Sales
FROM customers c
LEFT JOIN orders o
    ON c.Customer_ID = o.Customer_ID;



-- Q13. Display all products along with their order details.
-- Products without orders should also appear.

-- WRITE BELOW
SELECT
    p.Product_ID,
    p.Product_Name,
    p.Category,
    o.Order_ID,
    o.Quantity
FROM orders o
RIGHT JOIN products p
    ON o.Product_ID = p.Product_ID;



-- Q14. Create every possible combination of
-- Sales Channel and Product Category.

-- WRITE BELOW
SELECT
    s.Sales_Channel,
    p.Category
FROM
    (SELECT DISTINCT Sales_Channel FROM orders) s
CROSS JOIN
    (SELECT DISTINCT Category FROM products) p;



-- Q15. Display each employee along with their manager name.
-- Use SELF JOIN.

-- WRITE BELOW
SELECT
    e.Employee_Name AS Employee,
    m.Employee_Name AS Manager
FROM employees e
LEFT JOIN employees m
    ON e.Manager_ID = m.Employee_ID;



